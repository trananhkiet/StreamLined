"""Thin wrapper around the official `kaggle` CLI.

Credentials live only in memory (`Credentials`) and reach the CLI through the subprocess environment
(KAGGLE_USERNAME plus KAGGLE_KEY for legacy keys or KAGGLE_API_TOKEN for KGAT_ tokens). They are never written to disk, logged, or stored in run records, and every
CLI output is redacted before it is returned.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from .config import CIFAR100_KAGGLE_DATASET, DOCKER_IMAGE, TRAIN_SCRIPT, TrainConfig

NOTEBOOK_NAME = "skd_app_run.ipynb"


@dataclass(frozen=True)
class Credentials:
    username: str
    key: str

    def __repr__(self) -> str:  # never leak the key through st.write / logging / tracebacks
        return f"Credentials(username={self.username!r}, key='***')"

    __str__ = __repr__

    @classmethod
    def from_kaggle_json(cls, raw: bytes | str) -> "Credentials":
        data = json.loads(raw)
        return cls(username=str(data["username"]).strip(), key=str(data["key"]).strip())

    def is_api_token(self) -> bool:
        return self.key.startswith("KGAT_")

    def is_complete(self) -> bool:
        return bool(self.username and self.key)


@dataclass
class CliResult:
    ok: bool
    output: str
    returncode: int


def kaggle_command() -> list[str]:
    found = shutil.which("kaggle")
    if found:
        return [found]
    local = Path(sys.executable).with_name("kaggle")
    if local.exists():
        return [str(local)]
    return [sys.executable, "-m", "kaggle.cli"]


def redact(text: str, creds: Credentials | None) -> str:
    if creds and creds.key:
        text = text.replace(creds.key, "***")
    return text


def _env(creds: Credentials, config_dir: str) -> dict[str, str]:
    env = {k: v for k, v in os.environ.items() if not k.startswith("KAGGLE_")}
    env["KAGGLE_USERNAME"] = creds.username
    if creds.is_api_token():
        env["KAGGLE_API_TOKEN"] = creds.key  # new-style token from kaggle.com → Settings → API Tokens
    else:
        env["KAGGLE_KEY"] = creds.key  # legacy 32-hex key from kaggle.json
    # Point the CLI at an empty config dir so it never reads or writes a kaggle.json on this machine.
    env["KAGGLE_CONFIG_DIR"] = config_dir
    return env


def run_cli(args: list[str], creds: Credentials, timeout: int = 300, cwd: Path | None = None) -> CliResult:
    with tempfile.TemporaryDirectory(prefix="skd-kaggle-cfg-") as config_dir:
        try:
            proc = subprocess.run(
                kaggle_command() + args,
                env=_env(creds, config_dir),
                capture_output=True,
                text=True,
                timeout=timeout,
                cwd=cwd,
            )
        except FileNotFoundError:
            return CliResult(False, "Không tìm thấy kaggle CLI. Chạy `uv sync` trong thư mục app.", 127)
        except subprocess.TimeoutExpired:
            return CliResult(False, f"kaggle {' '.join(args[:2])} quá thời gian ({timeout}s)", 124)
    output = redact((proc.stdout or "") + (proc.stderr or ""), creds).strip()
    return CliResult(proc.returncode == 0, output, proc.returncode)


def verify(creds: Credentials) -> CliResult:
    return run_cli(["kernels", "list", "--mine", "--page-size", "1", "--csv"], creds, timeout=60)


# ---------------------------------------------------------------- kernel folder


def _cell(cell_type: str, source: str, idx: int) -> dict:
    cell = {"cell_type": cell_type, "id": f"cell-{idx}", "metadata": {}, "source": source.splitlines(keepends=True)}
    if cell_type == "code":
        cell.update({"execution_count": None, "outputs": []})
    return cell


def build_notebook(cfg: TrainConfig, script_text: str) -> dict:
    env = cfg.to_env()
    env_lines = "\n".join(f"os.environ[{k!r}] = {v!r}" for k, v in env.items())
    header = (
        "# SKD demo app run\n\n"
        f"Teacher **{cfg.teacher}** → student **{cfg.student}**, recipe **{cfg.recipe}**, seed {cfg.seed}.\n"
        "Generated by `app/` from `kaggle/streamlined_kd_cifar100.py`; only the environment cell differs."
    )
    cells = [
        _cell("markdown", header, 0),
        _cell("code", "import os\n" + env_lines + "\nprint({k: os.environ[k] for k in %r})\n" % sorted(env), 1),
        _cell("code", script_text, 2),
    ]
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def build_metadata(owner: str, slug: str, cfg: TrainConfig) -> dict:
    return {
        "id": f"{owner}/{slug}",
        "title": slug,
        "code_file": NOTEBOOK_NAME,
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [CIFAR100_KAGGLE_DATASET] if cfg.dataset == "cifar100" else [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
        "docker_image": DOCKER_IMAGE,
        "machine_shape": "NvidiaTeslaT4",
    }


def build_kernel_dir(kernel_dir: Path, owner: str, slug: str, cfg: TrainConfig, script: Path = TRAIN_SCRIPT) -> Path:
    kernel_dir.mkdir(parents=True, exist_ok=True)
    notebook = build_notebook(cfg, script.read_text())
    (kernel_dir / NOTEBOOK_NAME).write_text(json.dumps(notebook, indent=1) + "\n")
    (kernel_dir / "kernel-metadata.json").write_text(json.dumps(build_metadata(owner, slug, cfg), indent=2) + "\n")
    return kernel_dir


# ---------------------------------------------------------------- remote operations


def push(kernel_dir: Path, creds: Credentials) -> CliResult:
    return run_cli(["kernels", "push", "-p", str(kernel_dir)], creds, timeout=180)


_STATUS_RE = re.compile(r'status\s+"?(?:KernelWorkerStatus\.)?([A-Za-z_]+)"?', re.I)


def parse_status(output: str) -> str:
    match = _STATUS_RE.search(output)
    return match.group(1).lower() if match else "unknown"


def status(kernel_ref: str, creds: Credentials) -> tuple[str, CliResult]:
    result = run_cli(["kernels", "status", kernel_ref], creds, timeout=60)
    return (parse_status(result.output) if result.ok else "error"), result


def logs(kernel_ref: str, creds: Credentials) -> CliResult:
    return run_cli(["kernels", "logs", kernel_ref], creds, timeout=120)


def download_output(kernel_ref: str, dest: Path, creds: Credentials) -> CliResult:
    dest.mkdir(parents=True, exist_ok=True)
    return run_cli(["kernels", "output", kernel_ref, "-p", str(dest), "--force"], creds, timeout=900)


def parse_push(output: str) -> dict[str, str]:
    info: dict[str, str] = {}
    version = re.search(r"version\s+(\d+)", output, re.I)
    url = re.search(r"https://www\.kaggle\.com/\S+", output)
    if version:
        info["version"] = version.group(1)
    if url:
        info["url"] = url.group(0).rstrip(".")
    return info
